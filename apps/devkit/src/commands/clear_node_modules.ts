import type { Logger } from '@mono/node'
import { execSync } from 'child_process'
import fs from 'fs'
import { getRepoRootDirpath } from '../lib/getRepoRootDirpath'
import { glob } from 'glob'
import upath from 'upath'

export async function clearNodeModulesAction(_opts: unknown, { logger: log }: { logger: Logger }) {
  const root = getRepoRootDirpath()

  const paths = (
    await glob([
      '{apps,libs,packages}/*/{node_modules,package-lock.json}',
      'yarn.lock',
      'package-lock.json',
      'node_modules',
    ])
  )
    .map((dp) => {
      return upath.normalize(dp)
    })
    .sort()

  log.info('Deleting:')
  paths.forEach((p, i) => {
    return log.info('', i, p)
  })

  for (const p of paths.filter((p) => {
    return fs.existsSync(p)
  })) {
    fs.rmSync(p, { recursive: true, force: true })
  }

  log.info('Clearing yarn cache...')
  execSync('yarn cache clear', {
    stdio: 'inherit',
    cwd: root,
  })
}
